import test from 'node:test';
import assert from 'node:assert/strict';
import { PDFParse } from 'pdf-parse';
import {
  buildPrintablePdfHtml,
  generatePdfBuffer,
  sanitizePdfFilename,
  containsDevanagari,
} from './pdfGenerator';

test('sanitizePdfFilename normalizes titles cleanly to .pdf', () => {
  assert.equal(sanitizePdfFilename('Python Notes 2026!.pdf'), 'python-notes-2026.pdf');
  assert.equal(sanitizePdfFilename(undefined, 'My Study Guide'), 'my-study-guide.pdf');
  assert.equal(sanitizePdfFilename('   '), 'ultron-document.pdf');
});

test('containsDevanagari detects Hindi text accurately', () => {
  assert.equal(containsDevanagari('नमस्ते जगजीत'), true);
  assert.equal(containsDevanagari('Hello World'), false);
});

test('buildPrintablePdfHtml compiles KaTeX equations, Hindi, Markdown tables, and strips internal tags', () => {
  const html = buildPrintablePdfHtml({
    title: 'Physics & Maths Formula Sheet',
    content: [
      '# ऊर्जा और सूत्र',
      '',
      'नमस्ते जगजीत, यह हिंदी और मैथ्स टेस्ट है। $E = mc^2$ और $H_2O$।',
      '',
      '$$',
      'x = \\frac{-b \\pm \\sqrt{b^2 - 4ac}}{2a}',
      '$$',
      '',
      '| Formula | Meaning |',
      '| --- | --- |',
      '| $F = ma$ | Newton Second Law |',
      '',
      '```python',
      'def solve(a, b):',
      '    return a + b',
      '```',
      '',
      '[ACTION:{"type":"youtube_search","title":"hidden"}]',
    ].join('\n'),
  });

  assert.ok(html.includes('<span class="katex">'));
  assert.ok(html.includes('नमस्ते जगजीत'));
  assert.ok(html.includes('<table class="doc-table">'));
  assert.ok(html.includes('Newton Second Law'));
  assert.ok(html.includes('def solve(a, b):'));
  assert.equal(html.includes('\\frac'), false);
  assert.equal(html.includes('[ACTION:'), false);
  assert.equal(html.includes('[PDF:'), false);
});

test('generatePdfBuffer produces a valid readable English & Hindi PDF with Chromium HarfBuzz + KaTeX', async () => {
  const buf = await generatePdfBuffer({
    title: 'ULTRON Verification Document',
    content:
      '# Heading One\n\nThis is a real PDF generated by ULTRON.\n\n- Point A\n- Point B\n\nनमस्ते जगजीत, यह हिंदी टेस्ट है।',
  });

  assert.ok(Buffer.isBuffer(buf));
  assert.ok(buf.length > 2000);
  assert.equal(buf.subarray(0, 5).toString('utf8'), '%PDF-');

  const parser = new PDFParse({ data: buf });
  const parsed = await parser.getText();
  assert.ok(parsed.text.includes('ULTRON Verification Document'));
  assert.ok(parsed.text.includes('Point A'));
  assert.ok(parsed.text.includes('Point B'));
});

test('generatePdfBuffer renders LaTeX formulas, fractions, and tables cleanly into single-page PDF', async () => {
  const mathDoc = [
    '# Physics & Maths Formula Sheet',
    '',
    'ऊर्जा सूत्र (Energy Formula): $E = mc^2$ and Water $H_2O$.',
    '',
    '$$',
    'x = \\frac{-b \\pm \\sqrt{b^2 - 4ac}}{2a}',
    '$$',
    '',
    '| Formula | Meaning |',
    '| --- | --- |',
    '| $F = ma$ | Newton Second Law |',
    '| $E = mc^2$ | Mass Energy Equivalence |',
  ].join('\n');

  const buf = await generatePdfBuffer({
    title: 'Science & Math Notes',
    content: mathDoc,
  });

  assert.equal(buf.subarray(0, 5).toString('utf8'), '%PDF-');
  const parser = new PDFParse({ data: buf });
  const parsed = await parser.getText();
  assert.equal(parsed.text.includes('\\frac'), false);
  assert.equal(parsed.text.includes('\\sqrt'), false);
  assert.ok(parsed.text.includes('Physics & Maths Formula Sheet'));
  assert.ok(parsed.text.includes('Newton Second Law'));
  assert.ok(parsed.text.includes('Mass Energy Equivalence'));
  assert.ok(parsed.text.includes('mc'));
  assert.ok(parsed.text.includes('±'));
  assert.equal(parsed.total, 1);
});

test('buildPrintablePdfHtml handles inline $$, spaced $, currency, bare LaTeX, and aligned matrices with zero KaTeX errors', () => {
  const html = buildPrintablePdfHtml({
    title: 'Advanced Mathematics',
    content: [
      'Inline display: $$\\nabla \\cdot E = \\frac{\\rho}{\\varepsilon_0}$$ inside sentence.',
      'Spaced math: $ a^2 + b^2 = c^2 $ and currency $5 to $10 should stay intact.',
      'Bare formula: \\int_0^\\infty e^{-x^2} dx = \\frac{\\sqrt{\\pi}}{2}',
      '$$',
      '\\begin{aligned}',
      'f(x) &= x^2 + 2x + 1 \\\\',
      '&= (x + 1)^2',
      '\\end{aligned}',
      '$$',
    ].join('\n\n'),
  });

  assert.equal(html.includes('katex-error'), false);
  assert.ok(html.includes('<span class="katex">'));
  assert.ok(html.includes('$5 to $10'));
  assert.ok(html.includes('katex-display'));
});
